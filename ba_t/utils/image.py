import torchvision.transforms as tvf


# RGB in [0, 255] -> float tensor (3,H,W) in [-1, 1]
ImgNorm = tvf.Compose([tvf.ToTensor(), tvf.Normalize((0.5, 0.5, 0.5), (0.5, 0.5, 0.5))])
